#!/usr/bin/env python3
"""Run the swarm simulation matrix and write docs/results/swarm.md (+ plots).

Builds test/swarm.c against the real src/firefly.c, once with the shipped
constants and once per alternative in ALTERNATIVES, then runs every
scenario for TRIALS random trials. Plots need matplotlib (skipped if absent).

Usage: python3 swarm_report.py [--quick]
"""
import os
import statistics
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "docs", "results")
IMG = os.path.join(HERE, "..", "docs", "img")
QUICK = "--quick" in sys.argv
TRIALS = 20 if QUICK else 100
MAX_S = 600

# (label, topology, nodes, clock drift +/-, detection probability)
SCENARIOS = [
    ("2 boards", "all", 2, 0.10, 0.9),
    ("10 boards, all see all", "all", 10, 0.10, 0.9),
    ("30 boards, all see all", "all", 30, 0.10, 0.9),
    ("10 in a ring", "ring", 10, 0.10, 0.9),
    ("16 in a 4x4 grid", "grid", 16, 0.10, 0.9),
    ("8 in a line", "line", 8, 0.10, 0.9),
    ("10 all, 50 % of flashes missed", "all", 10, 0.10, 0.5),
    ("10 all, +/-20 % clocks", "all", 10, 0.20, 0.9),
    ("10 all, ideal (no drift, no misses)", "all", 10, 0.0, 1.0),
]
SHIPPED = ("shipped: jump 1/2 + 3, refractory 34", "")
ALTERNATIVES = [
    ("alt: jump 1/4 + 6, refractory 36", "-DFF_COUPLING_SHIFT=2u -DFF_KICK=6u -DFF_REFRACTORY=36u"),
    ("first draft: jump 1/4 + 2, refractory 13", "-DFF_COUPLING_SHIFT=2u -DFF_KICK=2u -DFF_REFRACTORY=13u"),
]


def build(defs, exe):
    cmd = ["gcc", "-O2", "-Wall", "-Wextra", "-Werror", *defs.split(), "-o", exe,
           os.path.join(HERE, "swarm.c"), os.path.join(HERE, "..", "src", "firefly.c"), "-lm"]
    subprocess.run(cmd, check=True)


def run(exe, top, n, drift, pdet, trace=None):
    args = [exe, top, str(n), str(drift), str(pdet), str(TRIALS), str(MAX_S)]
    if trace:
        args.append(trace)
    out = subprocess.run(args, check=True, capture_output=True, text=True).stdout
    rows = [l.split(",") for l in out.strip().splitlines()]
    t = [float(r[5]) for r in rows]
    steady = [float(r[6]) for r in rows]
    spread = [float(r[7]) for r in rows if float(r[7]) >= 0]
    ok = sorted(x for x in t if x >= 0)
    q = lambda a, p: a[min(len(a) - 1, int(p * len(a)))] if a else float("nan")
    return dict(n_ok=len(ok), n=len(t), med=q(ok, .5), p95=q(ok, .95), mx=ok[-1] if ok else float("nan"),
                steady_med=statistics.median(steady), steady_min=min(steady),
                spread=statistics.median(spread) if spread else float("nan"), times=ok)


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(IMG, exist_ok=True)
    exe = "/tmp/firefly_swarm"
    build(SHIPPED[1], exe)
    lines = ["# Swarm simulation results", "",
             f"Generated by `test/swarm_report.py`: {TRIALS} random trials per row, {MAX_S} s each. "
             "Each board runs the real `src/firefly.c` with its own watchdog clock (uniform within the "
             "drift shown), a random start time and a random start phase. A board sees a neighbour's "
             "flash with the detection probability shown.", "",
             "- **synced**: trials that reached 5 volleys in a row in which every board flashed within the "
             "sync window (100 ms for all-see-all; plus 40 ms per extra hop across the network).",
             "- **time to sync**: from power-up to the first of those 5 volleys.",
             "- **steady**: share of volleys in the second half of the trial that were in sync.",
             "- **spread**: median time from first to last flash in a volley.", "",
             f"## Shipped constants ({SHIPPED[0]})", "",
             "| Scenario | Synced | Time to sync: median | p95 | max | Steady: median | worst trial | Spread (median) |",
             "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    shipped_results = {}
    for label, top, n, drift, pdet in SCENARIOS:
        trace = os.path.join("/tmp", "trace.csv") if label.startswith("10 boards") else None
        r = run(exe, top, n, drift, pdet, trace)
        shipped_results[label] = r
        lines.append(f"| {label} | {r['n_ok']}/{r['n']} | {r['med']:.1f} s | {r['p95']:.1f} s | {r['mx']:.1f} s "
                     f"| {r['steady_med']:.1f} % | {r['steady_min']:.1f} % | {r['spread']:.0f} ms |")
        print(lines[-1])

    lines += ["", "## Alternatives considered", "",
              "Same scenarios, other constants (see `test/param_sweep.c` for the lock-step search that "
              "short-listed them).", "",
              "| Constants | Scenario | Synced | Time to sync: median | p95 | Steady: worst trial |",
              "| --- | --- | --- | --- | --- | --- |"]
    for name, defs in [SHIPPED] + ALTERNATIVES:
        build(defs, exe + "_alt")
        for label, top, n, drift, pdet in SCENARIOS[1:6]:
            r = run(exe + "_alt", top, n, drift, pdet)
            lines.append(f"| {name} | {label} | {r['n_ok']}/{r['n']} | {r['med']:.1f} s | {r['p95']:.1f} s "
                         f"| {r['steady_min']:.1f} % |")
            print(lines[-1])

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        t, node = [], []
        for l in open("/tmp/trace.csv"):
            a, b = l.strip().split(",")
            t.append(float(a)); node.append(int(b))
        fig, ax = plt.subplots(figsize=(9, 3.2))
        ax.scatter(t, node, s=40, marker="|", color="#c0392b")
        ax.set_xlim(0, 20); ax.set_xlabel("time (s)"); ax.set_ylabel("board")
        ax.set_title("10 boards, +/-10 % clocks, 90 % detection: every flash in the first 20 s")
        fig.tight_layout(); fig.savefig(os.path.join(IMG, "swarm-raster.png"), dpi=130)
        fig, ax = plt.subplots(figsize=(9, 3.2))
        r = shipped_results["10 boards, all see all"]
        ax.hist(r["times"], bins=30, color="#2c3e50")
        ax.set_xlabel("time to sync (s)"); ax.set_ylabel("trials")
        ax.set_title(f"Time to sync, 10 boards, {r['n']} trials")
        fig.tight_layout(); fig.savefig(os.path.join(IMG, "swarm-sync-times.png"), dpi=130)
        lines += ["", "## Plots", "", "![raster](../img/swarm-raster.png)", "",
                  "![sync times](../img/swarm-sync-times.png)"]
    except ImportError:
        lines += ["", "_(plots skipped: matplotlib not installed)_"]

    open(os.path.join(OUT, "swarm.md"), "w").write("\n".join(lines) + "\n")
    print("wrote docs/results/swarm.md")


if __name__ == "__main__":
    main()
